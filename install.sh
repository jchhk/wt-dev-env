#!/usr/bin/env bash
# Idempotent: create the local config, generate the ccache config from it, hook env.sh into
# ~/.bashrc, report missing tools.   install.sh [--no-bashrc]
#   --no-bashrc   env.sh is sourced some other way (e.g. a system profile script)
set -euo pipefail
HERE="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
bashrc=1; [ "${1:-}" = --no-bashrc ] && bashrc=0
# shellcheck disable=SC1091
. "$HERE/shell/config.sh"

# local config (machine layout): a template with every setting commented out
if [ ! -e "$DEV_ENV_CONFIG" ]; then
    mkdir -p "$(dirname "$DEV_ENV_CONFIG")"
    cat > "$DEV_ENV_CONFIG" <<TEMPLATE
# dev-env machine layout (shell syntax). Defaults shown; uncomment to change, then run
# $HERE/install.sh again (it regenerates the ccache config) and open a new shell.
#DEV_ENV_BASE_DIR=\$HOME/development      # worktree containers; ccache base_dir
#DEV_ENV_CCACHE_DIR=\$HOME/.cache/ccache   # e.g. a dedicated disk
#DEV_ENV_CCACHE_SIZE=20G
#DEV_ENV_CPM_CACHE=\$HOME/.cache/CPM       # must stay outside DEV_ENV_BASE_DIR
#DEV_ENV_SDK_ROOT=\$HOME/.config/dev-env/sdks   # entries: sdk add <name> <dir>
TEMPLATE
    echo "created $DEV_ENV_CONFIG (defaults)"
fi

# ccache: generated file = local settings + the machine-independent part
mkdir -p "$HOME/.config/ccache"
target="$HOME/.config/ccache/ccache.conf"
if [ -L "$target" ]; then
    rm "$target"      # older dev-env versions symlinked a file of the repository here
elif [ -e "$target" ] && ! grep -q 'generated by dev-env' "$target"; then
    mv "$target" "$target.bak.$(date +%Y%m%d%H%M%S)"
    echo "backed up existing $target"
fi
{
    echo "# generated by dev-env/install.sh from $DEV_ENV_CONFIG; do not edit, change that file"
    echo "max_size = $DEV_ENV_CCACHE_SIZE"
    echo "cache_dir = $DEV_ENV_CCACHE_DIR"
    echo "base_dir = $DEV_ENV_BASE_DIR"
    echo
    cat "$HERE/ccache/ccache.conf.in"
} > "$target"
echo "ccache config -> $target (cache $DEV_ENV_CCACHE_DIR, max $DEV_ENV_CCACHE_SIZE, base_dir $DEV_ENV_BASE_DIR)"

# shell
if [ $bashrc = 1 ] && ! grep -qF "$HERE/shell/env.sh" "$HOME/.bashrc" 2>/dev/null; then
    printf '\n# dev-env tooling: ccache launcher, cmake presets, wt (see %s/README.md)\n[ -f "%s/shell/env.sh" ] && source "%s/shell/env.sh"\n' "$HERE" "$HERE" "$HERE" >> "$HOME/.bashrc"
    echo "added source line to ~/.bashrc"
fi

# cache directories
if mkdir -p "$DEV_ENV_CCACHE_DIR" 2>/dev/null && [ -w "$DEV_ENV_CCACHE_DIR" ]; then
    echo "ccache dir: $DEV_ENV_CCACHE_DIR"
else
    echo "WARNING: ccache dir $DEV_ENV_CCACHE_DIR is not usable; every compile will FAIL."
    echo "         Make it available or set DEV_ENV_CCACHE_DIR in $DEV_ENV_CONFIG and run install.sh again."
fi
mkdir -p "$DEV_ENV_CPM_CACHE" 2>/dev/null || echo "WARNING: CPM cache $DEV_ENV_CPM_CACHE cannot be created"
case "$(cd "$DEV_ENV_CPM_CACHE" 2>/dev/null && pwd -P)/" in "$DEV_ENV_BASE_DIR"/*)
    echo "WARNING: the CPM cache is below DEV_ENV_BASE_DIR; worktrees will not share ccache entries for dependencies." ;;
esac

# tools
missing=()
for t in git cmake make ccache mold; do command -v "$t" >/dev/null || missing+=("$t"); done
if [ ${#missing[@]} -gt 0 ]; then
    echo "missing tools: ${missing[*]} (install them with your package manager)"
fi
echo "done. Open a new shell or run: source $HERE/shell/env.sh"
